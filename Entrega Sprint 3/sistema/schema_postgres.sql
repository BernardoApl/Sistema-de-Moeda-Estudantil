-- Estrutura do banco dedicado à aplicação na Vercel.
CREATE TABLE instituicoes (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome text NOT NULL UNIQUE);
CREATE TABLE contas (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, perfil text NOT NULL CHECK(perfil IN ('aluno','professor','empresa')),
 nome text NOT NULL, email text NOT NULL UNIQUE, senha_hash text NOT NULL,
 documento text NOT NULL UNIQUE, rg text NOT NULL DEFAULT '', endereco text NOT NULL DEFAULT '',
 curso text NOT NULL DEFAULT '', departamento text NOT NULL DEFAULT '', telefone text NOT NULL DEFAULT '',
 instituicao_id integer REFERENCES instituicoes(id), saldo integer NOT NULL DEFAULT 0 CHECK(saldo >= 0),
 ativo integer NOT NULL DEFAULT 1 CHECK(ativo IN (0,1)),
 CHECK(perfil = 'empresa' OR instituicao_id IS NOT NULL)
);
CREATE UNIQUE INDEX contas_email_insensivel ON contas (lower(email));
CREATE TABLE vantagens (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, empresa_id integer NOT NULL REFERENCES contas(id),
 descricao text NOT NULL, foto text NOT NULL, custo integer NOT NULL CHECK(custo > 0),
 ativo integer NOT NULL DEFAULT 1
);
CREATE TABLE transferencias (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, professor_id integer NOT NULL REFERENCES contas(id),
 aluno_id integer NOT NULL REFERENCES contas(id), valor integer NOT NULL CHECK(valor > 0),
 motivo text NOT NULL CHECK(length(trim(motivo)) > 0), data_hora timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE TABLE creditos (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, professor_id integer NOT NULL REFERENCES contas(id),
 semestre text NOT NULL, valor integer NOT NULL DEFAULT 1000 CHECK(valor = 1000),
 data_hora timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'), UNIQUE(professor_id, semestre)
);
CREATE TABLE resgates (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, aluno_id integer NOT NULL REFERENCES contas(id),
 vantagem_id integer NOT NULL REFERENCES vantagens(id), valor integer NOT NULL CHECK(valor > 0),
 codigo text NOT NULL UNIQUE, data_hora timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'), utilizado_em timestamp
);
CREATE TABLE notificacoes (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conta_id integer NOT NULL REFERENCES contas(id), destinatario text NOT NULL,
 assunto text NOT NULL, mensagem text NOT NULL, enviado integer NOT NULL DEFAULT 0,
 data_hora timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
