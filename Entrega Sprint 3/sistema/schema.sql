PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS instituicoes (id INTEGER PRIMARY KEY, nome TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS contas (
 id INTEGER PRIMARY KEY, perfil TEXT NOT NULL CHECK(perfil IN ('aluno','professor','empresa')),
 nome TEXT NOT NULL, email TEXT NOT NULL UNIQUE COLLATE NOCASE, senha_hash TEXT NOT NULL,
 documento TEXT NOT NULL UNIQUE, rg TEXT NOT NULL DEFAULT '', endereco TEXT NOT NULL DEFAULT '',
 curso TEXT NOT NULL DEFAULT '', departamento TEXT NOT NULL DEFAULT '', telefone TEXT NOT NULL DEFAULT '',
 instituicao_id INTEGER REFERENCES instituicoes(id), saldo INTEGER NOT NULL DEFAULT 0 CHECK(saldo >= 0),
 ativo INTEGER NOT NULL DEFAULT 1 CHECK(ativo IN (0,1)),
 CHECK(perfil = 'empresa' OR instituicao_id IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS vantagens (
 id INTEGER PRIMARY KEY, empresa_id INTEGER NOT NULL REFERENCES contas(id),
 descricao TEXT NOT NULL, foto TEXT NOT NULL, custo INTEGER NOT NULL CHECK(custo > 0),
 ativo INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS transferencias (
 id INTEGER PRIMARY KEY, professor_id INTEGER NOT NULL REFERENCES contas(id),
 aluno_id INTEGER NOT NULL REFERENCES contas(id), valor INTEGER NOT NULL CHECK(valor > 0),
 motivo TEXT NOT NULL CHECK(length(trim(motivo)) > 0), data_hora TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS creditos (
 id INTEGER PRIMARY KEY, professor_id INTEGER NOT NULL REFERENCES contas(id),
 semestre TEXT NOT NULL, valor INTEGER NOT NULL DEFAULT 1000 CHECK(valor = 1000),
 data_hora TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(professor_id, semestre)
);
CREATE TABLE IF NOT EXISTS resgates (
 id INTEGER PRIMARY KEY, aluno_id INTEGER NOT NULL REFERENCES contas(id),
 vantagem_id INTEGER NOT NULL REFERENCES vantagens(id), valor INTEGER NOT NULL CHECK(valor > 0),
 codigo TEXT NOT NULL UNIQUE, data_hora TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, utilizado_em TEXT
);
CREATE TABLE IF NOT EXISTS notificacoes (
 id INTEGER PRIMARY KEY, conta_id INTEGER NOT NULL REFERENCES contas(id), destinatario TEXT NOT NULL,
 assunto TEXT NOT NULL, mensagem TEXT NOT NULL, enviado INTEGER NOT NULL DEFAULT 0,
 data_hora TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
